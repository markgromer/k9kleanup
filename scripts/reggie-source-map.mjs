#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";

const target = process.cwd();
const sourceRoot = fs.existsSync(path.join(target, "src", "app")) ? "src" : "";
const scanRoots = [sourceRoot && path.join(target, sourceRoot), path.join(target, "app"), path.join(target, "components"), path.join(target, "pages")]
  .filter(Boolean)
  .filter((root, index, roots) => fs.existsSync(root) && roots.indexOf(root) === index);
const outputPath = path.join(target, sourceRoot, "generated", "reggie-source-map.ts");
const entries = [];

writeDeploymentIdentity();

for (const root of scanRoots) {
  for (const filePath of walk(root)) {
    const relativePath = toPosix(path.relative(target, filePath));
    if (!/\.(?:jsx|tsx)$/.test(filePath)
      || /(?:^|\/)(?:admin|api|generated)(?:\/|$)/.test(relativePath)
      || /(?:^|\/)components\/(?:admin-|customer-dashboard|internal-support|nurture|reggie-)/.test(relativePath)) continue;
    const lines = fs.readFileSync(filePath, "utf8").split(/\r?\n/);
    let symbol = componentName(relativePath);
    for (let index = 0; index < lines.length; index += 1) {
      const line = lines[index];
      const symbolMatch = line.match(/(?:export\s+)?(?:default\s+)?(?:async\s+)?function\s+([A-Z][A-Za-z0-9_$]*)|(?:export\s+)?const\s+([A-Z][A-Za-z0-9_$]*)\s*=/);
      if (symbolMatch) symbol = symbolMatch[1] || symbolMatch[2] || symbol;
      for (const match of line.matchAll(/data-(reggie-id|component|section|testid)\s*=\s*["']([^"']+)["']/g)) {
        add({ type: match[1] === "reggie-id" ? "reggieId" : match[1], value: match[2], filePath: relativePath, line: index + 1, column: (match.index || 0) + 1, symbol });
      }
      for (const match of line.matchAll(/>\s*([^<>{}\n][^<>{}\n]{7,180}?)\s*</g)) {
        const value = cleanText(match[1]);
        if (value.length >= 8 && !/[=;]$/.test(value)) add({ type: "text", value, filePath: relativePath, line: index + 1, column: (match.index || 0) + 1, symbol });
      }
    }
  }
}

entries.sort((left, right) => left.filePath.localeCompare(right.filePath) || left.line - right.line || left.type.localeCompare(right.type));
fs.mkdirSync(path.dirname(outputPath), { recursive: true });
const generatedSource = `// Generated by scripts/reggie-source-map.mjs. Do not edit by hand.\nexport const reggieSourceMap = ${JSON.stringify(entries.slice(0, 5000), null, 2)} as const;\n`;
writeLfIfChanged(outputPath, generatedSource);
const pagesOutputPath = path.join(target, "functions", "_generated", "reggie-source-map.ts");
if (fs.existsSync(path.join(target, "functions"))) {
  fs.mkdirSync(path.dirname(pagesOutputPath), { recursive: true });
  writeLfIfChanged(pagesOutputPath, generatedSource);
}
console.log(`Reggie source map: ${entries.length} entries -> ${toPosix(path.relative(target, outputPath))}`);

function writeDeploymentIdentity() {
  const buildCommitVariables = [
    "WORKERS_CI_COMMIT_SHA",
    "CF_PAGES_COMMIT_SHA",
    "RENDER_GIT_COMMIT",
    "VERCEL_GIT_COMMIT_SHA",
    "REGGIE_DEPLOY_COMMIT_SHA",
  ];
  const supplied = buildCommitVariables
    .map((name) => ({ name, value: String(process.env[name] ?? "").trim().toLowerCase() }))
    .find((entry) => entry.value);
  if (!supplied) return;
  if (!/^[a-f0-9]{40}$/.test(supplied.value)) {
    throw new Error(`${supplied.name} must contain the exact 40-character deployment commit SHA.`);
  }

  const identitySource = `// Generated deterministically by the deployment build. Do not hand-edit.\nexport const reggieDeploymentIdentity = {\n  commit: ${JSON.stringify(supplied.value)},\n  installedVersion: "0.5.51",\n  generatedAt: "",\n} as const;\n`;
  const identityPaths = [path.join(target, sourceRoot, "generated", "reggie-deployment-identity.ts")];
  if (fs.existsSync(path.join(target, "functions"))) {
    identityPaths.push(path.join(target, "functions", "_generated", "reggie-deployment-identity.ts"));
  }
  for (const identityPath of identityPaths) {
    fs.mkdirSync(path.dirname(identityPath), { recursive: true });
    writeLfIfChanged(identityPath, identitySource);
  }
  console.log(`Reggie deployment identity: ${supplied.value} from ${supplied.name}`);
}

function writeLfIfChanged(filePath, source) {
  const normalized = String(source).replace(/\r\n/g, "\n");
  if (fs.existsSync(filePath) && fs.readFileSync(filePath, "utf8") === normalized) return false;
  fs.writeFileSync(filePath, normalized);
  return true;
}

function add(entry) {
  if (!entry.value || entries.some((current) => current.type === entry.type && current.value === entry.value && current.filePath === entry.filePath && current.line === entry.line)) return;
  entries.push(entry);
}

function walk(root) {
  const results = [];
  for (const entry of fs.readdirSync(root, { withFileTypes: true })) {
    if (["node_modules", ".next", ".git", ".open-next"].includes(entry.name)) continue;
    const fullPath = path.join(root, entry.name);
    if (entry.isDirectory()) results.push(...walk(fullPath));
    else results.push(fullPath);
  }
  return results;
}

function componentName(relativePath) {
  const name = path.basename(relativePath).replace(/\.[^.]+$/, "");
  return name === "page" ? path.basename(path.dirname(relativePath)) || "Page" : name;
}

function cleanText(value) {
  return value
    .replace(/&amp;/g, "&")
    .replace(/&nbsp;/g, " ")
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/\s+/g, " ")
    .trim();
}

function toPosix(value) {
  return value.split(path.sep).join("/");
}
