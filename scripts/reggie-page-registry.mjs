function compareEntries(left, right) { if (left.path === "/") return -1; if (right.path === "/") return 1; if (left.dynamic !== right.dynamic) return left.dynamic ? 1 : -1; return left.path.localeCompare(right.path); }

function parseCli(argv) {
  const options = { command: "sync", root: process.cwd(), path: "", expectPath: "", json: false };
  const values = [...argv];
  if (values[0] && !values[0].startsWith("-")) options.command = values.shift();
  while (values.length) {
    const key = values.shift();
    if (key === "--root") options.root = values.shift() || options.root;
    else if (key === "--path") options.path = values.shift() || "";
    else if (key === "--expect-path") options.expectPath = values.shift() || "";
    else if (key === "--json") options.json = true;
    else if (key === "--help" || key === "-h") options.command = "help";
    else throw new Error(`Unknown option ${key}.`);
  }
  return options;
}

function printHelp() {
  console.log(`Usage:
  node scripts/reggie-page-registry.mjs sync [--root <repo>] [--expect-path </route>] [--json]
  node scripts/reggie-page-registry.mjs check --path </route> [--root <repo>] [--json]
  node scripts/reggie-page-registry.mjs list [--root <repo>] [--json]

sync discovers source routes and writes the generated registry. --expect-path fails unless a concrete route was created.
check fails when a requested landing-page path is invalid, reserved, or already handled by an existing route.`);
}

async function main() {
  const options = parseCli(process.argv.slice(2));
  if (options.command === "help") return printHelp();
  if (options.command === "check") {
    const result = validateRequestedPagePath(options.root, options.path);
    console.log(options.json ? JSON.stringify(result) : `${result.ok ? "available" : "blocked"}: ${result.path} - ${result.reason}`);
    if (!result.ok) process.exitCode = 2;
    return;
  }
  if (options.command === "list") {
    const entries = discoverPageRegistry(options.root);
    console.log(options.json ? JSON.stringify(entries, null, 2) : entries.map((entry) => `${entry.path}\t${entry.dynamic ? "dynamic" : "page"}\t${entry.sourceFile}`).join("\n"));
    return;
  }
  if (options.command !== "sync") throw new Error(`Unknown command ${options.command}.`);
  const result = syncPageRegistry(options.root, { expectPath: options.expectPath });
  const summary = { ok: true, pages: result.entries.length, changed: result.changed, target: toPosix(path.relative(path.resolve(options.root), result.target)), fingerprint: result.fingerprint };
  console.log(options.json ? JSON.stringify(summary) : `${result.changed ? "Updated" : "Verified"} ${summary.target} with ${summary.pages} source-backed routes.`);
}

