#!/usr/bin/env node

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const PAGE_FILE = /^page\.(?:[cm]?[jt]sx?|mdx?)$/i;
const PAGES_FILE = /\.(?:[cm]?[jt]sx?|mdx?)$/i;
const REGISTRY_START = "REGGIE_PAGE_REGISTRY_JSON_START";
const REGISTRY_END = "REGGIE_PAGE_REGISTRY_JSON_END";
const PUBLIC_EXTENSIONS = new Set([".js", ".jsx", ".ts", ".tsx", ".mjs", ".cjs", ".md", ".mdx"]);
const RESERVED_PREFIXES = ["/admin", "/api", "/_next", "/.well-known"];
const RESERVED_FILES = new Set(["/favicon.ico", "/robots.txt", "/sitemap.xml"]);

export function discoverPageRegistry(rootValue, options = {}) {
  const root = path.resolve(rootValue);
  const discovered = new Map();
  for (const appRoot of routeRoots(root, "app")) scanAppRouter(root, appRoot, discovered);
  for (const pagesRoot of routeRoots(root, "pages")) scanPagesRouter(root, pagesRoot, discovered);

  const dynamicPages = [...discovered.values()].filter((entry) => entry.dynamic);
  const adoptionCandidates = [
    ...readExistingRegistry(root),
    ...readLegacyDashboardProfiles(root),
    ...readSitemapPaths(root),
    ...(Array.isArray(options.adoptEntries) ? options.adoptEntries : []),
  ];
  for (const candidate of adoptionCandidates) adoptCandidate(candidate, dynamicPages, discovered);

  const entries = [...discovered.values()].filter((entry) => isPublicPath(entry.path));
  entries.sort(compareEntries);
  return entries;
}

export function writePageRegistry(rootValue, entriesValue, options = {}) {
  const root = path.resolve(rootValue);
  const entries = entriesValue.map(normalizeEntry).filter((entry) => isPublicPath(entry.path)).sort(compareEntries);
  const target = options.target ? path.resolve(root, options.target) : generatedRegistryPath(root);
  const serialized = JSON.stringify(entries, null, 2);
  const fingerprint = `sha256-${crypto.createHash("sha256").update(serialized).digest("hex")}`;
  const source = [
    "// Generated by scripts/reggie-page-registry.mjs. Do not hand-edit this file.",
    `// ${REGISTRY_START}`,
    ...serialized.split("\n").map((line) => `// ${line}`),
    `// ${REGISTRY_END}`,
    "",
    `export const reggiePageRegistry = ${serialized} as const;`,
    "",
    `export const reggiePageRegistryFingerprint = ${JSON.stringify(fingerprint)};`,
    "",
  ].join("\n");
  const targets = [target];
  if (fs.existsSync(path.join(root, "functions", "_lib"))) targets.push(path.join(root, "functions", "_generated", "reggie-page-registry.ts"));
  let changed = false;
  for (const output of targets) {
    fs.mkdirSync(path.dirname(output), { recursive: true });
    const previous = fs.existsSync(output) ? fs.readFileSync(output, "utf8") : "";
    if (previous === source) continue;
    fs.writeFileSync(output, source);
    changed = true;
  }
  return { target, targets, fingerprint, changed, entries };
}

export function syncPageRegistry(rootValue, options = {}) {
  const entries = discoverPageRegistry(rootValue, options);
  const result = writePageRegistry(rootValue, entries, options);
  if (options.expectPath) {
    const expected = normalizePath(options.expectPath);
    const exact = entries.find((entry) => entry.path === expected && !entry.dynamic);
    if (!exact) {
      const dynamic = entries.find((entry) => entry.dynamic && patternMatches(entry.path, expected));
      const detail = dynamic ? `; it is only covered by dynamic route ${dynamic.path}` : "";
      throw new Error(`Expected a concrete source route at ${expected}, but none was discovered${detail}.`);
    }
  }
  return result;
}

export function validateRequestedPagePath(rootValue, value) {
  const raw = String(value ?? "").trim();
  const pagePath = normalizePath(raw);
  if (!raw || !raw.startsWith("/")) return { ok: false, path: pagePath, reason: "Page paths must start with /." };
  if (raw.includes("?") || raw.includes("#") || raw.includes("\\")) return { ok: false, path: pagePath, reason: "Page paths cannot include a query, fragment, or backslash." };
  if (["[", "]", "(", ")", "@", "*"].some((character) => pagePath.includes(character)) || /%2f|%5c/i.test(pagePath)) return { ok: false, path: pagePath, reason: "Use a concrete path without route syntax or encoded slashes." };
  if (pagePath.split("/").some(unsafeRequestedPageSegment)) return { ok: false, path: pagePath, reason: "The page path contains an unsafe, encoded, or overly long segment." };
  if (!isPublicPath(pagePath)) return { ok: false, path: pagePath, reason: "That path is reserved for site infrastructure." };
  const entries = discoverPageRegistry(rootValue);
  const conflict = entries.find((entry) => entry.path === pagePath);
  if (conflict) return { ok: false, path: pagePath, reason: "A public page already exists at this path.", conflict };
  return { ok: true, path: pagePath, reason: "This path is available." };
}

function scanAppRouter(root, appRoot, output) {
  for (const file of walk(appRoot)) {
    if (!PAGE_FILE.test(path.basename(file))) continue;
    const relativeDirectory = toPosix(path.relative(appRoot, path.dirname(file)));
    const segments = relativeDirectory === "." ? [] : relativeDirectory.split("/");
    if (segments.some((segment) => segment.startsWith("_") || isInterceptingSegment(segment))) continue;
    const routeSegments = segments.filter((segment) => !isRouteGroup(segment) && !segment.startsWith("@"));
    const pagePath = normalizePath(routeSegments.join("/"));
    if (!isPublicPath(pagePath)) continue;
    const source = safeRead(file);
    const dynamic = routeSegments.some(isDynamicSegment);
    const entry = {
      path: pagePath,
      title: dynamic ? titleFromPath(pagePath) : sourceTitle(source) || titleFromPath(pagePath),
      kind: inferKind(pagePath),
      router: "app",
      sourceFile: toPosix(path.relative(root, file)),
      dynamic,
      pattern: pagePath,
      discoveredBy: "source",
    };
    addEntry(output, entry);
    for (const concretePath of concreteStaticParams(source, pagePath)) {
      addEntry(output, { ...entry, path: concretePath, title: titleFromPath(concretePath), dynamic: false, pattern: pagePath });
    }
  }
}

function scanPagesRouter(root, pagesRoot, output) {
  for (const file of walk(pagesRoot)) {
    if (!PAGES_FILE.test(file)) continue;
    const relative = toPosix(path.relative(pagesRoot, file));
    const extension = path.extname(relative);
    if (!PUBLIC_EXTENSIONS.has(extension.toLowerCase())) continue;
    const withoutExtension = relative.slice(0, -extension.length);
    const segments = withoutExtension.split("/");
    if (segments[0] === "api" || segments.some((segment) => segment.startsWith("_"))) continue;
    if (["404", "500"].includes(segments.at(-1) ?? "")) continue;
    if (segments.at(-1) === "index") segments.pop();
    const pagePath = normalizePath(segments.join("/"));
    if (!isPublicPath(pagePath)) continue;
    const source = safeRead(file);
    const dynamic = segments.some(isDynamicSegment);
    addEntry(output, {
      path: pagePath,
      title: dynamic ? titleFromPath(pagePath) : sourceTitle(source) || titleFromPath(pagePath),
      kind: inferKind(pagePath),
      router: "pages",
      sourceFile: toPosix(path.relative(root, file)),
      dynamic,
      pattern: pagePath,
      discoveredBy: "source",
    });
  }
}

function adoptCandidate(candidateValue, dynamicPages, output) {
  if (!candidateValue || typeof candidateValue !== "object") return;
  const candidate = normalizeEntry(candidateValue);
  if (!candidate.path || candidate.dynamic || !isPublicPath(candidate.path)) return;
  const exact = output.get(candidate.path);
  if (exact) {
    if (candidate.title && candidate.title !== titleFromPath(candidate.path)) exact.title = candidate.title;
    if (["service", "location", "blog"].includes(candidate.kind)) exact.kind = candidate.kind;
    return;
  }
  const pattern = dynamicPages.find((entry) => patternMatches(entry.path, candidate.path));
  if (!pattern) return;
  const finiteSourceRoutes = [...output.values()].filter((entry) => !entry.dynamic && entry.pattern === pattern.path && entry.discoveredBy === "source");
  if (finiteSourceRoutes.length) return;
  addEntry(output, {
    ...pattern,
    path: candidate.path,
    title: candidate.title || titleFromPath(candidate.path),
    kind: candidate.kind || pattern.kind,
    dynamic: false,
    pattern: pattern.path,
    discoveredBy: normalizeDiscovery(candidate.discoveredBy),
    ownership: candidate.ownership,
  });
}

function readExistingRegistry(root) {
  const candidates = [
    path.join(root, "src", "generated", "reggie-page-registry.ts"),
    path.join(root, "generated", "reggie-page-registry.ts"),
  ];
  for (const file of candidates) {
    const source = safeRead(file);
    const parsed = parseRegistryMarker(source);
    if (parsed.length) return parsed.map((entry) => ({ ...entry, discoveredBy: normalizeDiscovery(entry.discoveredBy) }));
  }
  return [];
}

function readLegacyDashboardProfiles(root) {
  const candidates = [
    path.join(root, "src", "lib", "dashboard-site-profile.ts"),
    path.join(root, "lib", "dashboard-site-profile.ts"),
  ];
  const entries = [];
  for (const file of candidates) {
    const source = safeRead(file);
    if (!source) continue;
    const objectPattern = /\{[^{}]{0,1200}\bpath\s*:\s*["'`]([^"'`]+)["'`][^{}]{0,1200}\}/gs;
    for (const match of source.matchAll(objectPattern)) {
      const block = match[0];
      const title = block.match(/\btitle\s*:\s*["'`]([^"'`]+)["'`]/)?.[1] ?? "";
      const kind = block.match(/\bkind\s*:\s*["'`](page|service|location|blog)["'`]/)?.[1] ?? inferKind(match[1]);
      entries.push({ path: match[1], title, kind, discoveredBy: "legacy-profile" });
    }
  }
  return entries;
}

function readSitemapPaths(root) {
  const files = [
    ...candidateFiles(root, "app/sitemap"),
    ...candidateFiles(root, "app/sitemap"),
  ];
  const entries = [];
  for (const file of files) {
    const source = safeRead(file);
    for (const match of source.matchAll(/["'`]\/(?!\/)([A-Za-z0-9._~!$&'()*+,;=:@%/-]*)["'`]/g)) {
      const pagePath = normalizePath(`/${match[1]}`);
      entries.push({ path: pagePath, title: titleFromPath(pagePath), kind: inferKind(pagePath), discoveredBy: "sitemap" });
    }
  }
  return entries;
}

function candidateFiles(root, relativeWithoutExtension) {
  return [...PUBLIC_EXTENSIONS].map((extension) => path.join(root, `${relativeWithoutExtension}${extension}`)).filter((file) => fs.existsSync(file));
}

function parseRegistryMarker(source) {
  if (!source.includes(REGISTRY_START) || !source.includes(REGISTRY_END)) return [];
  const body = source.split(REGISTRY_START)[1].split(REGISTRY_END)[0]
    .split(/\r?\n/)
    .map((line) => line.replace(/^\s*\/\/\s?/, ""))
    .join("\n")
    .trim();
  try { const value = JSON.parse(body); return Array.isArray(value) ? value : []; } catch { return []; }
}

function routeRoots(root, name) {
  return [path.join(root, name), path.join(root, "src", name)].filter((candidate) => fs.existsSync(candidate) && fs.statSync(candidate).isDirectory());
}

function generatedRegistryPath(root) {
  if (fs.existsSync(path.join(root, "src", "app")) || fs.existsSync(path.join(root, "src", "pages")) || fs.existsSync(path.join(root, "src", "generated"))) {
    return path.join(root, "src", "generated", "reggie-page-registry.ts");
  }
  return path.join(root, "generated", "reggie-page-registry.ts");
}

function walk(directory) {
  const results = [];
  if (!fs.existsSync(directory)) return results;
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    if (entry.name === "node_modules" || entry.name === ".next" || entry.name === ".git" || entry.name === ".reggie") continue;
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) results.push(...walk(fullPath));
    else if (entry.isFile()) results.push(fullPath);
  }
  return results;
}

function addEntry(output, entryValue) {
  const entry = normalizeEntry(entryValue);
  if (!entry.path || !entry.sourceFile) return;
  const existing = output.get(entry.path);
  if (!existing || (existing.router === "pages" && entry.router === "app")) output.set(entry.path, entry);
}

function normalizeEntry(value) {
  const source = value && typeof value === "object" ? value : {};
  const pagePath = normalizePath(source.path);
  const dynamic = Boolean(source.dynamic || hasDynamicSegment(pagePath));
  return {
    id: cleanId(source.id) || pageIdentity(pagePath),
    path: pagePath,
    title: cleanTitle(source.title) || titleFromPath(pagePath),
    kind: ["service", "location", "blog"].includes(source.kind) ? source.kind : inferKind(pagePath),
    router: source.router === "pages" ? "pages" : "app",
    sourceFile: toPosix(String(source.sourceFile ?? "")),
    dynamic,
    pattern: normalizePath(source.pattern || pagePath),
    discoveredBy: normalizeDiscovery(source.discoveredBy),
    ownership: normalizeOwnership(source.ownership, source.discoveredBy),
    authority: "site-git",
  };
}

function pageIdentity(pagePath) {
  return `page:${normalizePath(pagePath).toLowerCase()}`;
}

function cleanId(value) {
  const candidate = String(value ?? "").trim();
  return /^[a-z0-9][a-z0-9:._/-]{0,199}$/i.test(candidate) ? candidate : "";
}

function normalizeOwnership(value, discovery) {
  if (["structured", "source", "hybrid", "generated"].includes(value)) return value;
  return ["sitemap", "legacy-profile", "registry", "mission"].includes(discovery) ? "hybrid" : "source";
}

function normalizeDiscovery(value) {
  return ["source", "sitemap", "legacy-profile", "registry", "mission"].includes(value) ? value : "registry";
}

function normalizePath(value) {
  let candidate = String(value ?? "").trim().split("?")[0].split("#")[0].replace(/\\/g, "/").replace(/\/{2,}/g, "/");
  if (!candidate || candidate === "/" || candidate === ".") return "/";
  return `/${candidate.replace(/^\/+|\/+$/g, "")}`;
}

function isPublicPath(value) {
  const pagePath = normalizePath(value).toLowerCase();
  if (RESERVED_PREFIXES.some((prefix) => pagePath === prefix || pagePath.startsWith(`${prefix}/`))) return false;
  return !RESERVED_FILES.has(pagePath);
}

function patternMatches(patternValue, pathValue) {
  const pattern = normalizePath(patternValue);
  const pagePath = normalizePath(pathValue);
  if (!hasDynamicSegment(pattern)) return pattern === pagePath;
  let expression = "^";
  for (const segment of pattern.split("/").slice(1)) {
    if (/^\[\[\.\.\.[A-Za-z0-9_]+\]\]$/.test(segment)) expression += "(?:/[^/?#]+(?:/[^/?#]+)*)?";
    else if (/^\[\.\.\.[A-Za-z0-9_]+\]$/.test(segment)) expression += "/[^/?#]+(?:/[^/?#]+)*";
    else if (/^\[[A-Za-z0-9_]+\]$/.test(segment)) expression += "/[^/?#]+";
    else expression += `/${escapeRegExp(segment)}`;
  }
  return new RegExp(`${expression}/?$`).test(pagePath);
}

function inferKind(value) {
  const pagePath = normalizePath(value).toLowerCase();
  if (/^\/(?:services?|what-we-do)(?:\/|$)/.test(pagePath)) return "service";
  if (/^\/(?:locations?|service-areas?|areas?|cities)(?:\/|$)/.test(pagePath)) return "location";
  if (/^\/(?:blog|news|resources?|articles?)(?:\/|$)/.test(pagePath)) return "blog";
  return "page";
}

function titleFromPath(value) {
  const pagePath = normalizePath(value);
  if (pagePath === "/") return "Homepage";
  const segment = pagePath.split("/").filter(Boolean).at(-1) ?? "Page";
  if (isDynamicSegment(segment)) return segment.replace(/^\[+\.\.\.|^\[+|\]+$/g, "").replace(/([a-z])([A-Z])/g, "$1 $2").replace(/[-_]+/g, " ").replace(/\b\w/g, (letter) => letter.toUpperCase()) + " pages";
  return decodeSafely(segment).replace(/[-_]+/g, " ").replace(/\b\w/g, (letter) => letter.toUpperCase());
}

function sourceTitle(source) {
  const patterns = [
    /\btitle\s*:\s*["'`]([^"'`$]{1,180})["'`]/,
    /\bexport\s+const\s+title\s*=\s*["'`]([^"'`$]{1,180})["'`]/,
  ];
  for (const pattern of patterns) {
    const match = source.match(pattern);
    if (match?.[1]) return cleanTitle(match[1]);
  }
  return "";
}

function concreteStaticParams(source, routePattern) {
  const dynamicSegments = normalizePath(routePattern).split("/").filter(isDynamicSegment);
  if (dynamicSegments.length !== 1 || !/\bgenerateStaticParams\b/.test(source)) return [];
  const dynamicSegment = dynamicSegments[0];
  if (/^\[\[?\.\.\./.test(dynamicSegment)) return [];
  const paramName = dynamicSegment.replace(/^\[|\]$/g, "");
  const declaration = staticParamsDeclaration(source);
  if (!declaration) return [];
  const returned = topLevelReturnExpression(declaration.body);
  if (!returned) return [];
  const values = staticParamValuesFromExpression(source, returned.expression, paramName, declaration.bodyStart + returned.start);

  return [...values]
    .map((value) => normalizePath(routePattern.replace(dynamicSegment, value)))
    .filter((value) => isPublicPath(value) && !hasDynamicSegment(value));
}

function staticParamsDeclaration(source) {
  const patterns = [
    /\bfunction\s+generateStaticParams\s*\([^)]*\)\s*\{/g,
    /\b(?:const|let|var)\s+generateStaticParams(?:\s*:[^=;]{0,500})?\s*=\s*(?:async\s*)?(?:\([^)]*\)|[A-Za-z_$][\w$]*)\s*=>\s*\{/g,
  ];
  let earliest = null;
  for (const pattern of patterns) {
    const match = pattern.exec(source);
    if (!match || (earliest && match.index >= earliest.index)) continue;
    const open = match.index + match[0].lastIndexOf("{");
    const close = matchingDelimiter(source, open, "{", "}");
    if (close !== -1) earliest = { index: match.index, body: source.slice(open + 1, close), bodyStart: open + 1 };
  }
  return earliest;
}

function topLevelReturnExpression(body) {
  const depths = { "(": 0, "[": 0, "{": 0 };
  for (let index = 0; index < body.length;) {
    const skipped = skipJavaScriptLiteralOrComment(body, index);
    if (skipped !== index) { index = skipped; continue; }
    const character = body[index];
    if (character === "(" || character === "[" || character === "{") depths[character] += 1;
    else if (character === ")") depths["("] = Math.max(0, depths["("] - 1);
    else if (character === "]") depths["["] = Math.max(0, depths["["] - 1);
    else if (character === "}") depths["{"] = Math.max(0, depths["{"] - 1);
    else if (depths["("] === 0 && depths["["] === 0 && depths["{"] === 0 && body.startsWith("return", index) && !isIdentifierCharacter(body[index - 1]) && !isIdentifierCharacter(body[index + 6])) {
      const start = index + 6;
      return { expression: topLevelExpression(body, start), start };
    }
    index += 1;
  }
  return null;
}

function topLevelExpression(source, start) {
  const depths = { "(": 0, "[": 0, "{": 0 };
  let index = start;
  for (; index < source.length;) {
    const skipped = skipJavaScriptLiteralOrComment(source, index);
    if (skipped !== index) { index = skipped; continue; }
    const character = source[index];
    if (character === ";" && depths["("] === 0 && depths["["] === 0 && depths["{"] === 0) break;
    if (character === "(" || character === "[" || character === "{") depths[character] += 1;
    else if (character === ")") depths["("] = Math.max(0, depths["("] - 1);
    else if (character === "]") depths["["] = Math.max(0, depths["["] - 1);
    else if (character === "}") depths["{"] = Math.max(0, depths["{"] - 1);
    index += 1;
  }
  return source.slice(start, index).trim();
}

function staticParamValuesFromExpression(source, expressionValue, paramName, beforeIndex) {
  const expression = stripOuterParentheses(expressionValue.trim());
  const directArray = exactArrayInner(expression);
  if (directArray !== null) return objectArrayParamValues(directArray, paramName);

  const directVariable = expression.match(/^([A-Za-z_$][\w$]*)\s*(?:as\s+const)?$/);
  if (directVariable) {
    const array = declaredArrayInner(source, directVariable[1], beforeIndex);
    return array === null ? [] : objectArrayParamValues(array, paramName);
  }

  const mapMatch = expression.match(/^([A-Za-z_$][\w$]*)\s*\.\s*map\s*\(/);
  if (!mapMatch) return [];
  const open = expression.indexOf("(", mapMatch[0].length - 1);
  const close = matchingDelimiter(expression, open, "(", ")");
  if (open === -1 || close === -1 || expression.slice(close + 1).trim()) return [];
  const projection = staticMapProjection(expression.slice(open + 1, close), paramName);
  if (!projection) return [];
  const array = declaredArrayInner(source, mapMatch[1], beforeIndex);
  if (array === null) return [];
  return projection.kind === "strings" ? stringArrayValues(array) : objectArrayParamValues(array, projection.sourceProperty);
}

function staticMapProjection(callbackValue, paramName) {
  const callback = callbackValue.trim().replace(/^async\s+/, "");
  const arrow = topLevelArrowIndex(callback);
  if (arrow === -1) return null;
  const binding = callbackBinding(callback.slice(0, arrow));
  if (!binding) return null;
  const returnedObject = stripOuterParentheses(callback.slice(arrow + 2).trim());
  const projected = objectPropertyExpression(returnedObject, paramName);
  if (!projected) return null;
  const local = projected.match(/^([A-Za-z_$][\w$]*)$/)?.[1];
  if (local) {
    if (binding.kind === "element" && binding.local === local) return { kind: "strings" };
    if (binding.kind === "object" && binding.properties.has(local)) return { kind: "objects", sourceProperty: binding.properties.get(local) };
    return null;
  }
  const member = projected.match(/^([A-Za-z_$][\w$]*)\s*\.\s*([A-Za-z_$][\w$]*)$/);
  if (member && binding.kind === "element" && binding.local === member[1]) return { kind: "objects", sourceProperty: member[2] };
  return null;
}

function callbackBinding(value) {
  const binding = stripOuterParentheses(value.trim());
  if (/^[A-Za-z_$][\w$]*$/.test(binding)) return { kind: "element", local: binding };
  if (!binding.startsWith("{") || matchingDelimiter(binding, 0, "{", "}") !== binding.length - 1) return null;
  const properties = new Map();
  for (const part of splitTopLevel(binding.slice(1, -1))) {
    const match = part.trim().match(/^([A-Za-z_$][\w$]*)(?:\s*:\s*([A-Za-z_$][\w$]*))?$/);
    if (match) properties.set(match[2] || match[1], match[1]);
  }
  return properties.size ? { kind: "object", properties } : null;
}

function topLevelArrowIndex(source) {
  const depths = { "(": 0, "[": 0, "{": 0 };
  for (let index = 0; index < source.length;) {
    const skipped = skipJavaScriptLiteralOrComment(source, index);
    if (skipped !== index) { index = skipped; continue; }
    const character = source[index];
    if (source.startsWith("=>", index) && depths["("] === 0 && depths["["] === 0 && depths["{"] === 0) return index;
    if (character === "(" || character === "[" || character === "{") depths[character] += 1;
    else if (character === ")") depths["("] = Math.max(0, depths["("] - 1);
    else if (character === "]") depths["["] = Math.max(0, depths["["] - 1);
    else if (character === "}") depths["{"] = Math.max(0, depths["{"] - 1);
    index += 1;
  }
  return -1;
}

function declaredArrayInner(source, variable, beforeIndex) {
  const pattern = new RegExp(`\\b(?:const|let|var)\\s+${escapeRegExp(variable)}(?:\\s*:[^=;]{0,1000})?\\s*=\\s*\\[`, "g");
  let selected = null;
  for (const match of source.matchAll(pattern)) {
    if ((match.index ?? source.length) >= beforeIndex) break;
    const open = (match.index ?? 0) + match[0].lastIndexOf("[");
    const close = matchingDelimiter(source, open, "[", "]");
    if (close !== -1 && close < beforeIndex) selected = source.slice(open + 1, close);
  }
  return selected;
}

function exactArrayInner(expression) {
  if (!expression.startsWith("[")) return null;
  const close = matchingDelimiter(expression, 0, "[", "]");
  if (close === -1 || !/^(?:\s*|\s+as\s+const\s*)$/.test(expression.slice(close + 1))) return null;
  return expression.slice(1, close);
}

function objectArrayParamValues(arrayInner, paramName) {
  const values = [];
  for (const itemValue of splitTopLevel(arrayInner)) {
    const property = objectPropertyExpression(stripOuterParentheses(itemValue.trim()), paramName);
    const literal = property ? javaScriptStringLiteral(property) : null;
    if (literal !== null && safeStaticParamValue(literal)) values.push(literal);
  }
  return values;
}

function stringArrayValues(arrayInner) {
  const values = [];
  for (const item of splitTopLevel(arrayInner)) {
    const literal = javaScriptStringLiteral(stripOuterParentheses(item.trim()));
    if (literal !== null && safeStaticParamValue(literal)) values.push(literal);
  }
  return values;
}

function objectPropertyExpression(objectValue, propertyName) {
  const object = stripOuterParentheses(objectValue.trim());
  if (!object.startsWith("{") || matchingDelimiter(object, 0, "{", "}") !== object.length - 1) return "";
  for (const part of splitTopLevel(object.slice(1, -1))) {
    const candidate = part.trim();
    if (candidate === propertyName) return propertyName;
    const colon = topLevelColonIndex(candidate);
    if (colon === -1) continue;
    const key = candidate.slice(0, colon).trim();
    const decodedKey = /^[A-Za-z_$][\w$]*$/.test(key) ? key : javaScriptStringLiteral(key);
    if (decodedKey === propertyName) return candidate.slice(colon + 1).trim();
  }
  return "";
}

function topLevelColonIndex(source) {
  const depths = { "(": 0, "[": 0, "{": 0 };
  for (let index = 0; index < source.length;) {
    const skipped = skipJavaScriptLiteralOrComment(source, index);
    if (skipped !== index) { index = skipped; continue; }
    const character = source[index];
    if (character === ":" && depths["("] === 0 && depths["["] === 0 && depths["{"] === 0) return index;
    if (character === "(" || character === "[" || character === "{") depths[character] += 1;
    else if (character === ")") depths["("] = Math.max(0, depths["("] - 1);
    else if (character === "]") depths["["] = Math.max(0, depths["["] - 1);
    else if (character === "}") depths["{"] = Math.max(0, depths["{"] - 1);
    index += 1;
  }
  return -1;
}

function splitTopLevel(source) {
  const parts = [];
  const depths = { "(": 0, "[": 0, "{": 0 };
  let start = 0;
  for (let index = 0; index < source.length;) {
    const skipped = skipJavaScriptLiteralOrComment(source, index);
    if (skipped !== index) { index = skipped; continue; }
    const character = source[index];
    if (character === "," && depths["("] === 0 && depths["["] === 0 && depths["{"] === 0) { parts.push(source.slice(start, index)); start = index + 1; }
    else if (character === "(" || character === "[" || character === "{") depths[character] += 1;
    else if (character === ")") depths["("] = Math.max(0, depths["("] - 1);
    else if (character === "]") depths["["] = Math.max(0, depths["["] - 1);
    else if (character === "}") depths["{"] = Math.max(0, depths["{"] - 1);
    index += 1;
  }
  parts.push(source.slice(start));
  return parts.filter((part) => part.trim());
}

function stripOuterParentheses(value) {
  let result = value.trim();
  while (result.startsWith("(") && matchingDelimiter(result, 0, "(", ")") === result.length - 1) result = result.slice(1, -1).trim();
  return result;
}

function matchingDelimiter(source, openIndex, open, close) {
  if (openIndex < 0 || source[openIndex] !== open) return -1;
  let depth = 1;
  for (let index = openIndex + 1; index < source.length;) {
    const skipped = skipJavaScriptLiteralOrComment(source, index);
    if (skipped !== index) { index = skipped; continue; }
    if (source[index] === open) depth += 1;
    else if (source[index] === close && --depth === 0) return index;
    index += 1;
  }
  return -1;
}

function skipJavaScriptLiteralOrComment(source, index) {
  const character = source[index];
  if (character === '"' || character === "'" || character === "`") {
    for (let cursor = index + 1; cursor < source.length; cursor += 1) {
      if (source[cursor] === "\\") { cursor += 1; continue; }
      if (source[cursor] === character) return cursor + 1;
    }
    return source.length;
  }
  if (source.startsWith("//", index)) { const end = source.indexOf("\n", index + 2); return end === -1 ? source.length : end + 1; }
  if (source.startsWith("/*", index)) { const end = source.indexOf("*/", index + 2); return end === -1 ? source.length : end + 2; }
  return index;
}

function javaScriptStringLiteral(value) {
  const source = value.trim().replace(/\s+as\s+const\s*$/, "");
  const quote = source[0];
  if (!['"', "'", "`"].includes(quote)) return null;
  const end = skipJavaScriptLiteralOrComment(source, 0);
  if (end !== source.length || source.at(-1) !== quote) return null;
  if (quote === "`" && source.includes("${")) return null;
  let decoded = "";
  for (let index = 1; index < source.length - 1; index += 1) {
    const character = source[index];
    if (character !== "\\") { decoded += character; continue; }
    const escaped = source[++index];
    if (escaped === undefined) return null;
    const simple = { n: "\n", r: "\r", t: "\t", b: "\b", f: "\f", v: "\v", "0": "\0" };
    if (Object.hasOwn(simple, escaped)) decoded += simple[escaped];
    else if (escaped === "x" && /^[0-9a-f]{2}$/i.test(source.slice(index + 1, index + 3))) { decoded += String.fromCharCode(Number.parseInt(source.slice(index + 1, index + 3), 16)); index += 2; }
    else if (escaped === "u" && /^[0-9a-f]{4}$/i.test(source.slice(index + 1, index + 5))) { decoded += String.fromCharCode(Number.parseInt(source.slice(index + 1, index + 5), 16)); index += 4; }
    else decoded += escaped;
  }
  return decoded;
}

function safeStaticParamValue(value) {
  return Boolean(value && value.length <= 100 && value !== "." && value !== ".." && !/[\\/?#]/.test(value) && !/%2f|%5c/i.test(value));
}

function unsafeRequestedPageSegment(segment) {
  if (segment.length > 100) return true;
  let decoded = "";
  try { decoded = decodeURIComponent(segment); } catch { return true; }
  const containsControl = [...decoded].some((character) => character.charCodeAt(0) <= 31);
  return decoded === "." || decoded === ".." || containsControl || ["\\", "/", "?", "#", "[", "]", "(", ")", "@", "*"].some((character) => decoded.includes(character));
}

function isIdentifierCharacter(value) { return Boolean(value && /[A-Za-z0-9_$]/.test(value)); }

function cleanTitle(value) { return String(value ?? "").replace(/\\[nrt]/g, " ").replace(/\s+/g, " ").trim().slice(0, 180); }
function isRouteGroup(segment) { return /^\([^.)][^)]*\)$/.test(segment); }
function isInterceptingSegment(segment) { return /^\(\.{1,3}\)/.test(segment); }
function isDynamicSegment(segment) { return /^\[(?:\[)?(?:\.\.\.)?[A-Za-z0-9_]+\](?:\])?$/.test(segment); }
function hasDynamicSegment(value) { return normalizePath(value).split("/").some(isDynamicSegment); }
function toPosix(value) { return value.replaceAll(path.sep, "/"); }
function safeRead(file) { try { return fs.readFileSync(file, "utf8"); } catch { return ""; } }
function decodeSafely(value) { try { return decodeURIComponent(value); } catch { return value; } }
